// Generates app/theme-tokens.css — the light and dark RGB triplets behind every
// Tailwind color class in the app. Run: node scripts/gen-theme-tokens.mjs
//
// [2026-11-08] Dark mode. The app paints with literal palette classes
// (bg-cream-50, text-ink-warm-900, text-gray-500, bg-emerald-100 …) in ~290
// files. Instead of touching each one, tailwind.config.ts points those
// palettes at CSS variables, and this file supplies the variables twice:
// once on :root (the exact Tailwind / v11 values, so light mode is pixel-
// identical to before) and once on .dark.
//
// Dark rules, per family step (Tailwind's own scale as the source):
//   50 / 100 / 200 / 300  → the family's dark end blended into the page
//                           colour, so "tint" backgrounds and hairline
//                           borders stay tints and hairlines on dark.
//   400 / 500             → unchanged (icons, mid text, solid fills).
//   600                   → step 500 (text-X-600 lightens a notch).
//   700 / 800 / 900 / 950 → steps 300 / 200 / 100 / 50 (text flips light).
// Gray-ish families get the same rule, so text-gray-900 becomes near-white
// and bg-gray-50 becomes a slightly raised dark surface.
// cream, ink-warm and brand are hand-set below — they are the v11 chrome and
// deserve exact values rather than a formula.
import colors from 'tailwindcss/colors.js';
import { writeFileSync } from 'node:fs';

const FAMILIES = ['gray','slate','zinc','neutral','stone','red','orange','amber','yellow','lime','green','emerald','teal','cyan','sky','blue','indigo','violet','purple','fuchsia','pink','rose'];
const STEPS = [50,100,200,300,400,500,600,700,800,900,950];

const PAGE = '#141311';   // dark page (cream-50 in dark)
const hex2rgb = (h) => { const s = h.replace('#',''); return [0,2,4].map(i => parseInt(s.slice(i,i+2),16)); };
const trip = (rgb) => rgb.map(Math.round).join(' ');
const mix = (a, b, t) => a.map((v,i) => v*t + b[i]*(1-t)); // t = share of a

const light = {}; const dark = {};
for (const fam of FAMILIES) {
  const f = colors[fam];
  for (const s of STEPS) light[`${fam}-${s}`] = trip(hex2rgb(f[s]));
  const P = hex2rgb(PAGE);
  dark[`${fam}-50`]  = trip(mix(hex2rgb(f[900]), P, 0.26));
  dark[`${fam}-100`] = trip(mix(hex2rgb(f[900]), P, 0.40));
  dark[`${fam}-200`] = trip(mix(hex2rgb(f[800]), P, 0.55));
  dark[`${fam}-300`] = trip(mix(hex2rgb(f[700]), P, 0.70));
  dark[`${fam}-400`] = trip(hex2rgb(f[400]));
  dark[`${fam}-500`] = trip(hex2rgb(f[500]));
  dark[`${fam}-600`] = trip(hex2rgb(f[500]));
  dark[`${fam}-700`] = trip(hex2rgb(f[300]));
  dark[`${fam}-800`] = trip(hex2rgb(f[200]));
  dark[`${fam}-900`] = trip(hex2rgb(f[100]));
  dark[`${fam}-950`] = trip(hex2rgb(f[50]));
}

// v11 chrome — exact values.
const hand = {
  light: {
    'cream-50': '#FBF9F4', 'cream-100': '#F5F2E9', 'cream-200': '#EBE6D8', 'cream-300': '#D9D2BD',
    'ink-warm-900': '#16140F', 'ink-warm-800': '#2A2722', 'ink-warm-700': '#46423A', 'ink-warm-500': '#6B6557',
    'ink-warm-400': '#9A9385', 'ink-warm-300': '#C7C0AF', 'ink-warm-200': '#E2DDCE', 'ink-warm-100': '#F1ECDD', 'ink-warm-50': '#FBF9F4',
    'brand': '#3e8692', 'brand-hover': '#2d6b75', 'brand-light': '#e8f4f5', 'brand-soft': '#EFF5F4', 'brand-dark': '#2d6470', 'brand-deep': '#1f4651',
    'surface': '#FFFFFF',
  },
  dark: {
    'cream-50': PAGE, 'cream-100': '#201E1B', 'cream-200': '#2E2B27', 'cream-300': '#403C36',
    'ink-warm-900': '#F3EFE6', 'ink-warm-800': '#E4DFD4', 'ink-warm-700': '#CDC6B8', 'ink-warm-500': '#A39C8E',
    'ink-warm-400': '#7F786B', 'ink-warm-300': '#5B554B', 'ink-warm-200': '#3A3632', 'ink-warm-100': '#272421', 'ink-warm-50': PAGE,
    'brand': '#4A96A2', 'brand-hover': '#5BA8B3', 'brand-light': '#163237', 'brand-soft': '#172C2E', 'brand-dark': '#7FBAC4', 'brand-deep': '#9DCFD6',
    'surface': '#1D1B18',
  },
};
for (const [k,v] of Object.entries(hand.light)) light[k] = trip(hex2rgb(v));
for (const [k,v] of Object.entries(hand.dark))  dark[k]  = trip(hex2rgb(v));

const block = (sel, map) => `${sel} {\n${Object.entries(map).map(([k,v]) => `  --c-${k}: ${v};`).join('\n')}\n}\n`;
const out = `/* GENERATED by scripts/gen-theme-tokens.mjs — do not edit by hand.
   Light = Tailwind defaults + v11 values (pixel-identical to pre-dark-mode).
   Dark  = see the rules in the generator. */
${block(':root', light)}
${block('.dark', dark)}`;
writeFileSync(new URL('../app/theme-tokens.css', import.meta.url), out);
console.log('wrote app/theme-tokens.css', Object.keys(light).length, 'tokens');
